import AppKit
import PasteCore
import UniformTypeIdentifiers

/// Records item boundaries and original bytes. Clipboard writes are tracked by change count.
@MainActor
final class ClipboardBridge {
    struct Source { let bundleID: String; let name: String }
    private let pasteboard: NSPasteboard
    private let sourceProvider: () -> Source
    private var observedChange: Int
    var currentText: String? { pasteboard.string(forType: .string) }
    static let payloadLimit = 32 * 1024 * 1024

    init(pasteboard: NSPasteboard = .general, sourceProvider: @escaping () -> Source = {
        let app = NSWorkspace.shared.frontmostApplication
        return Source(bundleID: app?.bundleIdentifier ?? "", name: app?.localizedName ?? "未知应用")
    }) {
        self.pasteboard = pasteboard
        self.sourceProvider = sourceProvider
        observedChange = pasteboard.changeCount
    }

    func capture(preferences: AppPreferences, paused: Bool) throws -> ClipItem? {
        guard pasteboard.changeCount != observedChange else { return nil }
        observedChange = pasteboard.changeCount
        guard preferences.monitoringEnabled, !paused else { return nil }
        let source = sourceProvider()
        let bundle = source.bundleID
        guard bundle != Bundle.main.bundleIdentifier,
              !preferences.ignoredBundleIDs.contains(bundle) else { return nil }
        let items = pasteboard.pasteboardItems ?? []
        guard items.count <= 1024 else { throw ClipboardError.tooManyFormats }
        let types = Set(items.flatMap(\.types).map(\.rawValue))
        // Markers are inspected before any payload is read.
        if preferences.ignoreConfidential && types.contains("org.nspasteboard.ConcealedType") { return nil }
        if preferences.ignoreTransient && types.contains("org.nspasteboard.TransientType") { return nil }
        if preferences.ignoreGenerated && types.contains("org.nspasteboard.AutoGeneratedType") { return nil }
        var payloads: [PasteboardRepresentation] = []
        var bytes = 0
        for (index, item) in items.enumerated() {
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                bytes += data.count
                guard bytes <= Self.payloadLimit else { throw ClipboardError.tooLarge }
                payloads.append(.init(type: type.rawValue, data: data, itemIndex: index))
                guard payloads.count <= 256, type.rawValue.utf8.count <= 1024 else { throw ClipboardError.tooManyFormats }
            }
        }
        guard !payloads.isEmpty else { return nil }
        let text = pasteboard.string(forType: .string) ?? plainString(from: payloads)
        guard text.utf8.count <= 2 * 1024 * 1024 else { throw ClipboardError.textTooLarge }
        let files = items.compactMap { item -> String? in
            guard let value = item.string(forType: .fileURL), let url = URL(string: value), url.isFileURL else { return nil }
            return url.path
        }
        let image = payloads.contains { representation in
            UTType(representation.type)?.conforms(to: .image) == true
        }
        let kind = ContentClassifier.classify(text: text, filePaths: files, hasImage: image)
        let title = files.first.map { URL(fileURLWithPath: $0).lastPathComponent }
            ?? text.split(whereSeparator: \.isNewline).first.map(String.init)
            ?? kind.displayName
        return ClipItem(title: String(title.prefix(160)), text: text, kind: kind,
                        sourceBundleID: bundle, sourceName: source.name,
                        representations: payloads, filePaths: files)
    }

    func write(_ clips: [ClipItem], plainText: Bool) throws {
        guard !clips.isEmpty else { throw ClipboardError.emptySelection }
        var objects: [NSPasteboardItem] = []
        if plainText {
            let text = clips.map { $0.text.isEmpty ? $0.filePaths.joined(separator: "\n") : $0.text }.joined(separator: "\n")
            guard !text.isEmpty else { throw ClipboardError.noPlainText }
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            objects = [item]
        } else {
            for clip in clips {
                let groups = Dictionary(grouping: clip.representations, by: \.itemIndex)
                if groups.isEmpty {
                    let item = NSPasteboardItem()
                    item.setString(clip.text, forType: .string)
                    objects.append(item)
                } else {
                    for index in groups.keys.sorted() {
                        let item = NSPasteboardItem()
                        for representation in groups[index] ?? [] {
                            item.setData(representation.data, forType: .init(representation.type))
                        }
                        objects.append(item)
                    }
                }
            }
        }
        pasteboard.clearContents()
        guard pasteboard.writeObjects(objects) else { throw ClipboardError.writeFailed }
        observedChange = pasteboard.changeCount
    }

    private func plainString(from representations: [PasteboardRepresentation]) -> String {
        for rep in representations {
            if rep.type == NSPasteboard.PasteboardType.rtf.rawValue,
               let value = NSAttributedString(rtf: rep.data, documentAttributes: nil) { return value.string }
            // HTML is stored verbatim. Cocoa's HTML importer can fetch external resources;
            // background capture must never load it simply to obtain a preview.
            if rep.type == NSPasteboard.PasteboardType.URL.rawValue,
               let value = String(data: rep.data, encoding: .utf8) { return value }
        }
        return ""
    }
}

enum ClipboardError: LocalizedError {
    case tooLarge, textTooLarge, tooManyFormats, emptySelection, noPlainText, writeFailed
    var errorDescription: String? {
        switch self {
        case .tooLarge: return "内容超过 32 MB，未保存到历史记录。"
        case .textTooLarge: return "文本超过 2 MB，未保存到历史记录。"
        case .tooManyFormats: return "剪贴板项目或格式过多，未保存到历史记录。"
        case .emptySelection: return "请选择一个项目。"
        case .noPlainText: return "此项目没有可粘贴的纯文本。"
        case .writeFailed: return "写入系统剪贴板失败，请重试。"
        }
    }
}
